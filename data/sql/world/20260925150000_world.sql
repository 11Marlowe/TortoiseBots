-- Level-appropriate bot enchants: curated candidate table + full-coverage seed rows.
--
-- Replaces the old top-tier-only template table (`ai_playerbot_enchants`, created
-- 20260824090000, seeded 20260922110000/20260922160000/20260923100000) with a
-- level-gated candidate pool. Every row carries the data the new selection needs:
--
--   min_level : character level implied by the source (trainer reqlevel else
--               ceil(enchanting_skill/5); formula ceil(required_skill_rank/5);
--               applied item required_level else item_level; auto-learned
--               ceil(req_skill_value/5)). Profession skill caps at 5x level.
--   tier      : source tier under the same owner rules as the gear pool
--               (rules-gear.md): 0 base (world/quest/vendor/trainer/allowed
--               dungeon), 1 end-game dungeon (maps 229/289/329/800),
--               2+ raid (map_type=2 maps). Lowest-tier source wins: an enchant
--               available from ANY allowed source counts as base.
--   rep       : 1 when the source item or its quest is reputation-gated.
--   premium   : 1 for the owner-approved top-tier list (task-enchants.md section 3):
--               only applied to epic items; anything else premium is skipped by
--               the selector even when allowed by tier.
--
-- Tier/rep classification was derived from live tw_world data (2026-09-25):
-- recipe/formula items -> creature/gameobject/reference loot -> spawns -> map;
-- item required_reputation_faction/rank + quest RequiredMinRepFaction; trainer
-- and auto-learned rows are always tier 0. Excluded by default (tier>0 or
-- rep=1): 55 rows covering 37 spells, e.g. Lifestealing/Unholy/Superior
-- Striking (Scholomance/Stratholme/BRS loot), Spell/Healing Power weapon and
-- Threat/Subtlety (AQ40/Naxxramas loot), rep-gated Mighty/Agility weapons,
-- Mana Regen/Healing bracers, Rift Tear and 2H Agility (Timbermaw/Zandalar).
-- Excluded non-premium rows: 2H Major Spirit/Intellect (BRS), Arcane/Nature
-- gloves (Emerald Sanctum), Cloak Agility (Karazhan), Superior Stamina /
-- Vampirism boots (Naxxramas), Greater Striking/Impact ladders stay allowed.
--
-- Junk excluded at generation (never inserted): QAEnchant/Test/Copy/Sharpen
-- Blade spells and payload-less spells (no SpellItemEnchantment id).
--
-- Quality ceiling (owner rule, enforced in C++ not SQL): grey/white items get
-- no enchant; green items only non-premium rows with min_level <= bot_level-10;
-- blue items non-premium rows with min_level <= bot_level; epic items anything
-- allowed incl. premium. Premium rows are marked but never picked for
-- non-epics.
--
-- Idempotent: DELETE + INSERT (candidate set is fully curated, not appended).
-- After apply: restart mangosd (or .reload ai_playerbot_enchant_candidates).
