-- Vanilla spec weight scales for random-bot gear scoring.
--
-- Source: shyalya-tortoise-wow@05ba90b2e00ef5ee861111ec5bde670929eedfa4
--         modules/mod-playerbots/sql/world/classic/ai_playerbot_weightscales.sql
--   (headerless HeidiSQL dump of the classic/ike3 weight scales, md5
--    6e9a6dbfce75330bcd2f811ec710b15c). Data-only port: the DROP/CREATE header
--   is deliberately omitted; the schema stays owned by
--   20260824090000_world.sql, the same treatment as the ai_playerbot_texts seed
--   in 20260913090000_world.sql. See docs/LICENSE_AUDIT.md for the donor grant
--   matrix (mod-playerbots: GPL-2.0, headerless data file).
--
-- Why this ships with the module: with ai_playerbot_weightscale_data empty,
-- RandomItemMgr::BuildItemInfoCache() bails out before it builds any stat
-- weight, so GetPlayerSpecId() returns 0 for every bot, PlayerbotFactory skips
-- its gear provisioning, and no upgrade is ever judged. The tables are seeded
-- together because either one alone leaves scoring dead.
--
-- Spec ids 16-19 (death knight) are intentionally absent: the target core has no
-- death knight class and random gear never selects those specs. Every other row
-- keeps its donor id. The module hardcodes spec ids (2, 3, 4, 5, 6, 14, 20, 21,
-- 22, 29, 31 in PlayerbotFactory.cpp:1901-2321 and RandomItemMgr.cpp:2816), so
-- the ids MUST NOT be renumbered or compacted.
--
-- The shipped id set is deleted before it is re-inserted so re-application is
-- idempotent (ai_playerbot_weightscale_data has no unique key and a duplicate
-- stat row would double-count a weight). Ids 16-19 are left untouched, so an
-- operator who already imported the full 32-spec dump keeps those rows.

